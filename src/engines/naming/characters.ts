export type Element = "木" | "火" | "土" | "金" | "水";
type Text3 = { "zh-Hant": string; "zh-Hans": string; en: string };

export interface NameChar {
  hant: string;
  hans: string;
  /** Pinyin with its tone mark, e.g. hán */
  pinyin: string;
  element: Element;
  /** The radical its element is read from (繁 form) */
  radical: string;
  meaning: Text3;
}

